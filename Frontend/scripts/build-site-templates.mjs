// Compiles the marketing page templates (src/site/*.html) into a TypeScript
// module so the server can render them without filesystem access (works on
// Node, Vercel and Cloudflare Workers alike). Runs before `dev` and `build`.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const siteDir = path.join(root, "src", "site");
const outFile = path.join(root, "src", "lib", "site", "templates.generated.ts");

const entries = fs
  .readdirSync(siteDir)
  .filter((f) => f.endsWith(".html"))
  .sort()
  .map(
    (f) =>
      `  ${JSON.stringify(f)}: ${JSON.stringify(fs.readFileSync(path.join(siteDir, f), "utf8").replace(/\r\n/g, "\n"))},`,
  );

const out = `// AUTO-GENERATED by scripts/build-site-templates.mjs from src/site/*.html — do not edit.
// Edit the HTML files instead; this file is rebuilt on \`npm run dev\` and \`npm run build\`.

export const templates: Record<string, string> = {
${entries.join("\n")}
};
`;

const previous = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
if (previous !== out) fs.writeFileSync(outFile, out);
console.log(`site templates: ${entries.length} pages compiled`);
